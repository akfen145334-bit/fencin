/**
 * Get current academic week based on a given date (defaults to current date)
 */
export function getCurrentAcademicWeek(targetDate: Date = new Date()): number {
  const y = targetDate.getFullYear();
  const m = String(targetDate.getMonth() + 1).padStart(2, '0');
  const d = String(targetDate.getDate()).padStart(2, '0');
  const dateStr = `${y}-${m}-${d}`;

  // Find exact matching week
  for (const item of academicWeeksCalendar) {
    if (dateStr >= item.start && dateStr <= item.end) {
      return item.week;
    }
  }

  // If in vacation or weekend, find closest next or previous week
  if (dateStr < academicWeeksCalendar[0].start) {
    return 1;
  }
  if (dateStr > academicWeeksCalendar[academicWeeksCalendar.length - 1].end) {
    return 37;
  }

  // Fallback: Find closest upcoming week
  for (let i = 0; i < academicWeeksCalendar.length; i++) {
    if (dateStr <= academicWeeksCalendar[i].end) {
      return academicWeeksCalendar[i].week;
    }
  }

  return 5; // Default: 5. Hafta (Ekim ortası)
}

/**
 * Get curriculum item for specific grade and week number
 */
export function getWeeklyItemForGradeAndWeek(grade: number, weekNumber: number): WeeklyCurriculumItem | undefined {
  const schedule = allGradeSchedules[grade] || allGradeSchedules[8];
  return schedule.find(item => item.weekNumber === weekNumber) || schedule[0];
}
